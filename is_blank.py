"""Проверка «значение пустое» для ветвлений внутри графа ComfyUI.

Зачем свой модуль вместо `easy isNone` (ComfyUI-Easy-Use): та нода начала
считать пустой строкой `""` только с коммита `d39b5e13` (2025-12-19), до него
реагировала лишь на настоящий `None`. Откат пина Easy-Use или rebuild машины на
старый хеш ломал бы ветвление **молча** — без ошибки, просто с пустым планом,
уехавшим в билдер промпта. Плюс её семантика жёсткая и неочевидная в ревью.

Модуль намеренно чистый stdlib — без ComfyUI, torch, folder_paths, чтобы его
можно было импортировать и тестировать вне ComfyUI.

Считается ПУСТЫМ:
    * `None`;
    * строка нулевой длины и строка только из пробельных символов
      (`" "`, `"\\n"`, `"\\t"`);
    * строка-заглушка после `strip()` + `lower()`: `null`, `none`, `undefined`,
      `nan` — так VLM и сериализаторы отдают «значения нет»;
    * пустой JSON-контейнер как текст: `{}`, `[]` (с пробелами внутри и вокруг);
    * пустой контейнер как объект: `[]`, `{}`, `()`, `set()`.

Считается НЕ пустым:
    * число `0` и `0.0` — **осознанное отличие от `easy isNone`**, которая
      считает ноль пустым (`any == 0`). Ноль сплошь и рядом валидное значение
      (upscale=0, creativity=0, denoise=0.0), и его молчаливое приравнивание к
      «значения нет» — частый источник сюрпризов в графе;
    * `False` — по той же причине (в `easy isNone` он пустой, т.к. `False == 0`):
      это ответ «нет», а не отсутствие ответа;
    * любая непустая строка, включая `"0"`, `"false"`, `"{\\"objects\\": []}"`;
    * любой другой объект (тензор, модель, image batch) — про них ничего не
      известно, а «пусто» по умолчанию опаснее, чем «не пусто».
"""

import re

# Текстовые заглушки «значения нет». Сверяются после strip() + lower().
_PLACEHOLDERS = frozenset({"null", "none", "undefined", "nan"})

# Пустой JSON-контейнер как текст: "{}", "{ }", "[]", "[\n]".
_EMPTY_JSON_CONTAINER_RE = re.compile(r"\{\s*\}|\[\s*\]")


def _is_blank_text(text):
    """Правила пустоты для строк (см. докстринг модуля)."""
    stripped = text.strip()
    if not stripped:
        return True
    if _EMPTY_JSON_CONTAINER_RE.fullmatch(stripped):
        return True
    return stripped.lower() in _PLACEHOLDERS


def is_blank(value):
    """`True`, если значение считается пустым. Всегда возвращает `bool`."""
    if value is None:
        return True
    if isinstance(value, str):
        return _is_blank_text(value)
    # Только точные типы-контейнеры: numpy/torch сюда не попадают, их `len()`
    # и truthiness неоднозначны и роняли бы прогон.
    if isinstance(value, (list, tuple, dict, set, frozenset)):
        return len(value) == 0
    # Числа (0 / 0.0), bool и всё остальное — не пустые.
    return False
